export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;

const cache = new Map<string, Uint8Array>();

export function glyph(ch: string): Uint8Array {
  const key = G[ch] ? ch : G[ch.toUpperCase()] ? ch.toUpperCase() : '?';
  let bits = cache.get(key);
  if (!bits) {
    bits = new Uint8Array(GLYPH_W * GLYPH_H);
    G[key]!.split('|').forEach((row, y) => [...row].forEach((c, x) => (bits![y * GLYPH_W + x] = c === '#' ? 1 : 0)));
    cache.set(key, bits);
  }
  return bits;
}

export const textWidth = (s: string, scale = 1): number => (s.length ? [...s].length * ADVANCE * scale - scale : 0);
